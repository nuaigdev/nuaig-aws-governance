/** Last login per Cognito sub, from the profile records the auth trigger maintains. */
async function fetchLastLogins(): Promise<Map<string, string>> {
  const logins = new Map<string, string>();
  let nextToken: string | null | undefined;

  do {
    const page = await data.models.UserProfile.list({
      limit: 200,
      nextToken: nextToken ?? undefined,
    });
    for (const profile of page.data ?? []) {
      if (profile.sub && profile.lastLoginAt) {
        logins.set(profile.sub, profile.lastLoginAt);
      }
    }
    nextToken = page.nextToken;
  } while (nextToken);

  return logins;
}

function attr(user: UserType, name: string): string {
  return user.Attributes?.find((a) => a.Name === name)?.Value ?? "";
}

function toPortalUser(
  user: UserType,
  groups: readonly string[],
  lastLogins: ReadonlyMap<string, string>,
): PortalUser {
  const sub = attr(user, "sub");
  return {
    username: user.Username ?? "",
    sub,
    email: attr(user, "email"),
    givenName: attr(user, "given_name"),
    familyName: attr(user, "family_name"),
    enabled: user.Enabled ?? false,
    status: normaliseStatus(user.UserStatus),
    groups: [...groups],
    createdAt: user.UserCreateDate?.toISOString() ?? "",
    lastLoginAt: lastLogins.get(sub) ?? null,
  };
}

function normaliseStatus(status: string | undefined): UserStatus {
  switch (status) {
    case "CONFIRMED":
    case "FORCE_CHANGE_PASSWORD":
    case "RESET_REQUIRED":
    case "UNCONFIRMED":
      return status;
    default:
      return "UNKNOWN";
  }
}
