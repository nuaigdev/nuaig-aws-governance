async function listUsers(): Promise<PortalUser[]> {
  const users = await listAllCognitoUsers();
  const lastLogins = await fetchLastLogins();

  const withGroups = await Promise.all(
    users.map(async (user) => {
      const groups = await listGroupsForUser(user.Username!);
      return toPortalUser(user, groups, lastLogins);
    }),
  );

  // Enabled users first, then alphabetically — the list is a working tool for
  // an admin, and disabled accounts are the ones they least often need.
  return withGroups.sort((a, b) => {
    if (a.enabled !== b.enabled) return a.enabled ? -1 : 1;
    return a.email.localeCompare(b.email);
  });
}

async function createUser(
  request: Extract<ReturnType<typeof parseOperation>, { operation: "createUser" }>,
  caller: ReturnType<typeof resolveCaller>,
) {
  const created = await cognito.send(
    new AdminCreateUserCommand({
      UserPoolId: USER_POOL_ID,
      Username: request.email,
      UserAttributes: [
        { Name: "email", Value: request.email },
        { Name: "email_verified", Value: "true" },
        { Name: "given_name", Value: request.givenName },
        { Name: "family_name", Value: request.familyName },
      ],
      // Cognito emails the temporary password. The user is forced to change it
      // and enrol in TOTP on first sign-in.
      DesiredDeliveryMediums: ["EMAIL"],
    }),
  );

  const username = created.User?.Username;
  if (!username) {
    throw new Error("Cognito did not return a username for the created user.");
  }

  for (const group of request.groups) {
    await cognito.send(
      new AdminAddUserToGroupCommand({
        UserPoolId: USER_POOL_ID,
        Username: username,
        GroupName: group,
      }),
    );
  }

  await writeAuditEvent(data, activeClient.clientId, caller, {
    action: "USER_CREATED",
    outcome: "SUCCESS",
    targetUser: username,
    detail: { email: request.email, groups: request.groups },
  });

  const groups = await listGroupsForUser(username);
  return toPortalUser(created.User!, groups, new Map());
}

async function disableUser(username: string, caller: ReturnType<typeof resolveCaller>) {
  assertAdminSafety(
    { targetUsername: username, kind: "disable" },
    caller.username,
    await listEnabledAdminUsernames(),
  );

  await cognito.send(
    new AdminDisableUserCommand({ UserPoolId: USER_POOL_ID, Username: username }),
  );

  // Disabling alone leaves existing tokens valid until they expire. Global
  // sign-out revokes them, so offboarding takes effect immediately rather than
  // up to an access token's lifetime later.
  await cognito.send(
    new AdminUserGlobalSignOutCommand({
      UserPoolId: USER_POOL_ID,
      Username: username,
    }),
  );

  await writeAuditEvent(data, activeClient.clientId, caller, {
    action: "USER_DISABLED",
    outcome: "SUCCESS",
    targetUser: username,
    detail: { sessionsRevoked: true },
  });

  return { username, enabled: false };
}

async function enableUser(username: string, caller: ReturnType<typeof resolveCaller>) {
  await cognito.send(
    new AdminEnableUserCommand({ UserPoolId: USER_POOL_ID, Username: username }),
  );

  await writeAuditEvent(data, activeClient.clientId, caller, {
    action: "USER_REENABLED",
    outcome: "SUCCESS",
    targetUser: username,
  });

  return { username, enabled: true };
}

async function setUserGroups(
  username: string,
  nextGroups: readonly string[],
  caller: ReturnType<typeof resolveCaller>,
) {
  const current = await listGroupsForUser(username);

  assertAdminSafety(
    { targetUsername: username, kind: "setGroups", nextGroups },
    caller.username,
    await listEnabledAdminUsernames(),
  );

  const toAdd = nextGroups.filter((g) => !current.includes(g));
  const toRemove = current.filter((g) => !nextGroups.includes(g));

  for (const group of toAdd) {
    await cognito.send(
      new AdminAddUserToGroupCommand({
        UserPoolId: USER_POOL_ID,
        Username: username,
        GroupName: group,
      }),
    );
  }

  for (const group of toRemove) {
    await cognito.send(
      new AdminRemoveUserFromGroupCommand({
        UserPoolId: USER_POOL_ID,
        Username: username,
        GroupName: group,
      }),
    );
  }

  // A user whose groups changed is carrying a token that still asserts the old
  // ones. Revoking forces a fresh token on next request, so a removed grant
  // stops applying immediately.
  if (toRemove.length > 0) {
    await cognito.send(
      new AdminUserGlobalSignOutCommand({
        UserPoolId: USER_POOL_ID,
        Username: username,
      }),
    );
  }

  await writeAuditEvent(data, activeClient.clientId, caller, {
    action: "USER_GROUPS_CHANGED",
    outcome: "SUCCESS",
    targetUser: username,
    detail: {
      previous: current,
      next: nextGroups,
      added: toAdd,
      removed: toRemove,
      sessionsRevoked: toRemove.length > 0,
    },
  });

  return { username, groups: nextGroups };
}

async function resendInvite(username: string, caller: ReturnType<typeof resolveCaller>) {
  await cognito.send(
    new AdminCreateUserCommand({
      UserPoolId: USER_POOL_ID,
      Username: username,
      MessageAction: "RESEND",
      DesiredDeliveryMediums: ["EMAIL"],
    }),
  );

  await writeAuditEvent(data, activeClient.clientId, caller, {
    action: "USER_INVITE_RESENT",
    outcome: "SUCCESS",
    targetUser: username,
  });

  return { username, invitationResent: true };
}

