import {
  AdminAddUserToGroupCommand,
  AdminCreateUserCommand,
  AdminDisableUserCommand,
  AdminEnableUserCommand,
  AdminListGroupsForUserCommand,
  AdminRemoveUserFromGroupCommand,
  AdminUserGlobalSignOutCommand,
  CognitoIdentityProviderClient,
  ListUsersCommand,
  ListUsersInGroupCommand,
  type UserType,
} from "@aws-sdk/client-cognito-identity-provider";
import { getAmplifyDataClientConfig } from "@aws-amplify/backend/function/runtime";
import { Amplify } from "aws-amplify";
import { generateClient } from "aws-amplify/data";
import type { AppSyncResolverEvent } from "aws-lambda";

// `$amplify/env/*` is generated by `ampx` at deploy time; a checked-in
// placeholder under .amplify/generated keeps a fresh clone typechecking.
import { env } from "$amplify/env/admin-users";

import { activeClient } from "../../../config";
import type { Schema } from "../../data/resource";
import { writeAuditEvent } from "../shared/audit";
import { resolveCaller } from "../shared/identity";
import {
  ADMIN_GROUP,
  assertAdminSafety,
  OperationError,
  parseOperation,
  type PortalUser,
  type UserStatus,
} from "./operations";

const { resourceConfig, libraryOptions } = await getAmplifyDataClientConfig(env);
Amplify.configure(resourceConfig, libraryOptions);

const data = generateClient<Schema>();
const cognito = new CognitoIdentityProviderClient();
const USER_POOL_ID = env.AMPLIFY_AUTH_USERPOOL_ID;

export const handler = async (
  event: AppSyncResolverEvent<{ operation: string; payload: unknown }>,
): Promise<unknown> => {
  const caller = resolveCaller(event);

  // AppSync already enforces the admin group on this mutation. Re-checking
  // here means the handler is still safe if that binding is ever loosened, and
  // it gives us an audit record of the attempt rather than a silent 401.
  if (!caller.groups.includes(ADMIN_GROUP)) {
    await writeAuditEvent(data, activeClient.clientId, caller, {
      action: "ACCESS_DENIED",
      outcome: "DENIED",
      detail: { reason: "not-an-admin", mutation: "manageUsers" },
    });
    throw new Error("Administrator access is required.");
  }

  const request = parseOperation(event.arguments.operation, event.arguments.payload);

  try {
    switch (request.operation) {
      case "listUsers":
        return await listUsers();

      case "createUser":
        return await createUser(request, caller);

      case "disableUser":
        return await disableUser(request.username, caller);

      case "enableUser":
        return await enableUser(request.username, caller);

      case "setUserGroups":
        return await setUserGroups(request.username, request.groups, caller);

      case "resendInvite":
        return await resendInvite(request.username, caller);
    }
  } catch (error) {
    if (error instanceof OperationError) {
      // Expected, admin-facing refusal (e.g. last-admin protection). Record it
      // and surface the message, which is written to be shown in the UI.
      await writeAuditEvent(data, activeClient.clientId, caller, {
        action: "ACCESS_DENIED",
        outcome: "DENIED",
        detail: {
          operation: event.arguments.operation,
          reason: error.message,
        },
      });
      throw new Error(error.message);
    }

    console.error("ADMIN_USERS_FAILED", {
      operation: event.arguments.operation,
      actorSub: caller.sub,
      error,
    });
    // Do not leak AWS error detail to the browser.
    throw new Error(
      `The operation could not be completed. The error has been logged.`,
    );
  }
};

