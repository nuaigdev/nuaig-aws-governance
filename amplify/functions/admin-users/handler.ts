async function listAllCognitoUsers(): Promise<UserType[]> {
  const users: UserType[] = [];
  let paginationToken: string | undefined;

  do {
    const page = await cognito.send(
      new ListUsersCommand({
        UserPoolId: USER_POOL_ID,
        Limit: 60,
        PaginationToken: paginationToken,
      }),
    );
    users.push(...(page.Users ?? []));
    paginationToken = page.PaginationToken;
  } while (paginationToken);

  return users;
}

async function listGroupsForUser(username: string): Promise<string[]> {
  const groups: string[] = [];
  let nextToken: string | undefined;

  do {
    const page = await cognito.send(
      new AdminListGroupsForUserCommand({
        UserPoolId: USER_POOL_ID,
        Username: username,
        Limit: 60,
        NextToken: nextToken,
      }),
    );
    groups.push(...(page.Groups ?? []).map((g) => g.GroupName!).filter(Boolean));
    nextToken = page.NextToken;
  } while (nextToken);

  return groups;
}

/** Usernames of admins who could actually sign in — disabled ones cannot. */
async function listEnabledAdminUsernames(): Promise<string[]> {
  const admins: string[] = [];
  let nextToken: string | undefined;

  do {
    const page = await cognito.send(
      new ListUsersInGroupCommand({
        UserPoolId: USER_POOL_ID,
        GroupName: ADMIN_GROUP,
        Limit: 60,
        NextToken: nextToken,
      }),
    );
    for (const user of page.Users ?? []) {
      if (user.Enabled && user.Username) admins.push(user.Username);
    }
    nextToken = page.NextToken;
  } while (nextToken);

  return admins;
}

