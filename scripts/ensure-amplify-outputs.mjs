/**
 * Ensures `amplify_outputs.json` exists so the app can be built and typechecked
 * on a fresh clone, before anyone has deployed a sandbox.
 *
 * `ampx sandbox` and `ampx pipeline-deploy` write the real file, which is
 * gitignored because its contents are per-environment. Without this, a fresh
 * clone fails at build with a module-not-found on a file that is *supposed* to
 * be absent — a confusing first experience.
 *
 * The placeholder is deliberately marked. `assertAmplifyConfigured()` in
 * `src/lib/amplify/client.ts` detects it and fails with an instruction to run
 * `npm run sandbox`, rather than letting the app start and then error on the
 * first network call with something opaque.
 */
import { existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const target = resolve(process.cwd(), "amplify_outputs.json");

if (existsSync(target)) {
  process.exit(0);
}

const placeholder = {
  $placeholder:
    "Generated by scripts/ensure-amplify-outputs.mjs. Run `npm run sandbox` to " +
    "deploy a backend and replace this with real outputs.",
  version: "1.4",
};

writeFileSync(target, `${JSON.stringify(placeholder, null, 2)}\n`);

console.log(
  "amplify_outputs.json was missing; wrote a placeholder.\n" +
    "Run `npm run sandbox` to deploy a backend and generate the real one.",
);
